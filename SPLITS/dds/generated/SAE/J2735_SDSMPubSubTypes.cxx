        bool SensorDataSharingMessagePubSubType::getKey(
                void* data,
                InstanceHandle_t* handle,
                bool force_md5)
        {
            if (!m_isGetKeyDefined)
            {
                return false;
            }

            SensorDataSharingMessage* p_type = static_cast<SensorDataSharingMessage*>(data);

            // Object that manages the raw buffer.
            eprosima::fastcdr::FastBuffer fastbuffer(reinterpret_cast<char*>(m_keyBuffer),
                    J2735_idl_SensorDataSharingMessage_max_key_cdr_typesize);

            // Object that serializes the data.
            eprosima::fastcdr::Cdr ser(fastbuffer, eprosima::fastcdr::Cdr::BIG_ENDIANNESS, eprosima::fastcdr::CdrVersion::XCDRv1);
        #if FASTCDR_VERSION_MAJOR == 1
            p_type->serializeKey(ser);
        #else
            eprosima::fastcdr::serialize_key(ser, *p_type);
        #endif // FASTCDR_VERSION_MAJOR == 1
            if (force_md5 || J2735_idl_SensorDataSharingMessage_max_key_cdr_typesize > 16)
            {
                m_md5.init();
        #if FASTCDR_VERSION_MAJOR == 1
                m_md5.update(m_keyBuffer, static_cast<unsigned int>(ser.getSerializedDataLength()));
        #else
                m_md5.update(m_keyBuffer, static_cast<unsigned int>(ser.get_serialized_data_length()));
        #endif // FASTCDR_VERSION_MAJOR == 1
                m_md5.finalize();
                for (uint8_t i = 0; i < 16; ++i)
                {
                    handle->value[i] = m_md5.digest[i];
                }
            }
            else
            {
                for (uint8_t i = 0; i < 16; ++i)
                {
                    handle->value[i] = m_keyBuffer[i];
                }
            }
            return true;
        }


